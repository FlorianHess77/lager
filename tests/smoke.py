"""Durchklick-Test am Handyformat mit Screenshots (python3 tests/smoke.py)."""
import asyncio, json, os, sys, threading, http.server, socketserver, functools
from playwright.async_api import async_playwright
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.environ.get('SHOTS', os.path.join(ROOT, 'tests', '_shots')); os.makedirs(OUT, exist_ok=True)
class Q(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *a): pass
srv = socketserver.ThreadingTCPServer(('127.0.0.1', 0), functools.partial(Q, directory=ROOT)); srv.daemon_threads = True
threading.Thread(target=srv.serve_forever, daemon=True).start()
BASE = f'http://127.0.0.1:{srv.server_address[1]}/'
errors = []
def check(cond, msg):
    print(('ok   ' if cond else 'FAIL ') + msg)
    if not cond: errors.append(msg)

async def run(theme):
    async with async_playwright() as p:
        b = await p.chromium.launch(args=['--use-fake-ui-for-media-stream', '--use-fake-device-for-media-stream'])
        ctx = await b.new_context(permissions=['camera'], viewport={'width': 390, 'height': 844}, device_scale_factor=2, has_touch=True, is_mobile=True, accept_downloads=True,
                                  locale='de-AT', color_scheme=theme)
        pg = await ctx.new_page()
        pg.on('pageerror', lambda e: errors.append(f'{theme}: JS-Fehler {e}'))
        pg.on('console', lambda m: m.type == 'error' and 'fonts.g' not in (m.location.get('url') or '') and 'models/clip' not in (m.location.get('url') or '') and errors.append(f'{theme}: console {m.text} {m.location.get("url")}'))
        await pg.goto(BASE); await pg.wait_for_timeout(600)
        shot = lambda n: pg.screenshot(path=f'{OUT}/{theme}-{n}.png', full_page=True)
        await shot('01-welcome')
        await pg.click('[data-n="Garage"]'); await pg.click('[data-n="Bad"]'); await pg.click('[data-n="Wohnzimmer"]')
        await pg.click('[data-a="createStarter"]'); await pg.wait_for_timeout(300)
        check(await pg.locator('.kc').count() == 6, f'{theme}: 6 Raumkarten')
        # Ding mit Foto einräumen
        items = [('Keller', 'Regal links', 'Akkuschrauber Bosch', 1, 'Werkzeug, Akku'), ('Keller', 'Regal links', 'Weihnachtsdeko', 3, 'Kisten'),
                 ('Keller', 'Weinregal', 'Rotwein Zweigelt', 6, ''), ('Werkstatt', 'Wand', 'Schraubenzieher-Set', 1, 'Werkzeug'),
                 ('Werkstatt', 'Lade 2', 'Schrauben 4x40', 2, ''), ('Küche', 'Speis', 'Nudeln', 1, ''), ('Garage', '', 'Winterreifen', 4, 'Auto')]
        for i, (room, place, name, qty, tags) in enumerate(items):
            await pg.goto(BASE + '#/'); await pg.wait_for_timeout(150)
            await pg.click('.nav-add'); await pg.wait_for_timeout(200)
            await pg.fill('#fName', name)
            await pg.click(f'#fRooms .chip:has-text("{room}")')
            await pg.fill('#fPlace', place)
            await pg.fill('#fQty', str(qty))
            await pg.fill('#fTags', tags)
            if i in (0, 3):
                await pg.set_input_files('#filePick', os.path.join(ROOT, 'tests', 'sample.jpg')); await pg.wait_for_timeout(500)
                check(await pg.locator('#fPhotos .pt').count() == 1, f'{theme}: Foto im Formular')
                if i == 0: await shot('03-form')
            if name == 'Nudeln': await pg.fill('#fMin', '2')
            await pg.click('button[type=submit]'); await pg.wait_for_timeout(250)
        check(len(await pg.evaluate("S.items")) == 7, f'{theme}: 7 Dinge gespeichert')
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(400)
        await shot('02-home')
        await pg.click('.kc:has-text("Keller")'); await pg.wait_for_timeout(300)
        await shot('04-room')
        check(await pg.locator('.shelf').count() == 2, f'{theme}: Keller hat 2 Plätze')
        await pg.click('.it:has-text("Akkuschrauber")'); await pg.wait_for_timeout(400)
        await shot('05-item')
        # Foto im Vollbild
        await pg.click('.gal .ph'); await pg.wait_for_timeout(400)
        check(await pg.locator('#viewer').is_visible(), f'{theme}: Foto öffnet im Vollbild')
        check(await pg.evaluate("!!document.querySelector('.vw-slide img').src"), f'{theme}: Vollbild-Foto geladen')
        await pg.screenshot(path=f'{OUT}/{theme}-05b-viewer.png')
        await pg.dblclick('.vw-slide', position={'x': 120, 'y': 300}); await pg.wait_for_timeout(200)
        check('scale(2.5)' in await pg.evaluate("document.querySelector('.vw-slide img').style.transform"), f'{theme}: Doppelklick zoomt')
        await pg.go_back(); await pg.wait_for_timeout(300)
        check(await pg.locator('#viewer').is_hidden() and '#/item/' in pg.url, f'{theme}: Zurück schließt Vollbild, Seite bleibt')
        # Suche mit Tippfehler / Mehrzahl / Umlaut
        for q, want in [('schraube', 'Schraubenzieher-Set'), ('akuschrauber', 'Akkuschrauber Bosch'), ('nudel', 'Nudeln'), ('werkzeug', 'Schraubenzieher-Set'), ('kuche', 'Nudeln'), ('winterreifen garage', 'Winterreifen')]:
            res = await pg.evaluate(f"search({q!r}).map(x=>x.it.name)")
            check(want in res, f'{theme}: Suche „{q}“ findet {want} ({res[:3]})')
        await pg.goto(BASE + '#/search'); await pg.wait_for_timeout(200)
        await pg.fill('#sq', 'schrauben'); await pg.wait_for_timeout(200)
        await shot('06-search')
        await pg.goto(BASE + '#/lists/low'); await pg.wait_for_timeout(200)
        check(await pg.locator('.it:has-text("Nudeln")').count() == 1, f'{theme}: Nudeln stehen auf „Wird knapp“')
        await pg.goto(BASE + '#/more'); await pg.wait_for_timeout(200); await shot('07-more')
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(200); await pg.click('.annex'); await pg.wait_for_timeout(400); await shot('08-newroom')
        await pg.keyboard.press('Escape')
        # ---- Neue Felder: Haltbarkeit, Preis, Garantie, Beleg, Barcode
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(150)
        await pg.click('.nav-add'); await pg.wait_for_timeout(200)
        await pg.fill('#fName', 'Bohrmaschine Makita')
        await pg.click('#fRooms .chip:has-text("Werkstatt")')
        await pg.click('.more-f summary')
        soon = await pg.evaluate("isoDay(new Date(Date.now()+5*864e5))")
        await pg.fill('#fExp', soon)
        await pg.fill('#fBought', '2025-03-01'); await pg.fill('#fPrice', '149,90')
        await pg.click('[data-a="fWarY"][data-y="2"]')
        check(await pg.input_value('#fWar') == '2027-03-01', f'{theme}: Garantie 2 Jahre ab Kauf')
        await pg.fill('#fCode', '4006381333931')
        await pg.evaluate("camTarget={docs:true}")
        await pg.set_input_files('#filePick', os.path.join(ROOT, 'tests', 'sample.jpg')); await pg.wait_for_timeout(500)
        check(await pg.locator('#fDocs .pt').count() == 1, f'{theme}: Beleg im Formular')
        await shot('09-form-more')
        await pg.click('button[type=submit]'); await pg.wait_for_timeout(300)
        it = await pg.evaluate("S.items.find(i=>i.name==='Bohrmaschine Makita')")
        check(it['price'] == 149.9 and it['warranty'] == '2027-03-01' and len(it['docs']) == 1 and it['barcode'] == '4006381333931', f'{theme}: Felder gespeichert {it.get("price")}')
        await pg.goto(BASE + '#/item/' + it['id']); await pg.wait_for_timeout(300)
        check(await pg.locator('.group.dl .badge.warn').count() >= 1, f'{theme}: Ablauf-Hinweis beim Ding')
        await shot('10-item-details')
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(200)
        check(await pg.locator('.pill:has-text("bald ab")').count() == 1, f'{theme}: Startseite zeigt „läuft bald ab“')
        await pg.goto(BASE + '#/lists/exp'); await pg.wait_for_timeout(200)
        check(await pg.locator('.it:has-text("Bohrmaschine")').count() == 1, f'{theme}: Liste „Läuft ab“')
        await pg.goto(BASE + '#/lists/war'); await pg.wait_for_timeout(200)
        check(await pg.locator('.it:has-text("Bohrmaschine")').count() == 1, f'{theme}: Liste „Garantie“')
        await shot('11-list-war')
        # Barcode-Suche + Scan-Auswertung
        check('Bohrmaschine Makita' in await pg.evaluate("search('4006381333931').map(x=>x.it.name)"), f'{theme}: Suche findet Barcode')
        await pg.evaluate("handleScan('4006381333931')"); await pg.wait_for_timeout(200)
        check('#/item/' + it['id'] in pg.url, f'{theme}: Scan eines bekannten Barcodes öffnet das Ding')
        kid = await pg.evaluate("S.rooms.find(r=>r.name==='Keller').id")
        await pg.evaluate(f"handleScan('https://florianhess77.github.io/lager/#/place/{kid}/Regal%20links')"); await pg.wait_for_timeout(300)
        check(await pg.locator('.hero h1:has-text("Regal links")').count() == 1 and await pg.locator('.it').count() == 2, f'{theme}: QR-Scan öffnet den Platz mit Inhalt')
        await shot('12-place')
        # Mehrere einräumen
        check(await pg.evaluate("JSON.stringify(parseBulk('Hammer\\n3x Schraubenzieher\\nVerlängerungskabel 2\\nSchrauben 4x40\\n- Kabelbinder (50)'))") == '[{"name":"Hammer","qty":1},{"name":"Schraubenzieher","qty":3},{"name":"Verlängerungskabel","qty":2},{"name":"Schrauben 4x40","qty":1},{"name":"Kabelbinder","qty":50}]', f'{theme}: Mengen beim Mehrfach-Einräumen erkannt')
        n0 = await pg.evaluate("S.items.length")
        await pg.click('.toolrow [data-a="bulkAdd"]'); await pg.wait_for_timeout(300)
        await pg.fill('#bkText', 'Hammer\n3x Schraubenzieher\nVerlängerungskabel 2')
        await shot('13-bulk')
        await pg.click('#bkGo'); await pg.wait_for_timeout(500)
        check(await pg.evaluate("S.items.length") == n0 + 3 and await pg.evaluate("S.items.find(i=>i.name==='Schraubenzieher').place") == 'Regal links', f'{theme}: 3 Dinge auf einmal eingeräumt')
        # QR-Aufkleber + Inventarliste
        await pg.goto(BASE + '#/labels'); await pg.wait_for_timeout(300)
        nl = await pg.locator('.lab').count()
        check(nl >= 3 and await pg.locator('.lab svg').count() == nl, f'{theme}: {nl} QR-Aufkleber in der Vorschau')
        await pg.locator('input[data-k]').first.check(); await pg.wait_for_timeout(100)
        check(await pg.locator('.lab').count() == nl + 1, f'{theme}: Auswahl ändert die Vorschau')
        await shot('14-labels')
        await pg.goto(BASE + '#/inventory'); await pg.wait_for_timeout(300)
        check(await pg.locator('.inv tbody tr').count() == await pg.evaluate("S.items.length") and '149,90' in await pg.inner_text('.inv-sum'), f'{theme}: Inventarliste mit Gesamtwert')
        await shot('15-inventory')
        await pg.emulate_media(media='print'); await pg.screenshot(path=f'{OUT}/{theme}-16-inventory-print.png', full_page=True); await pg.emulate_media(media='screen')
        # Fotoerkennung ohne Modell: kein Fehler, keine Vorschläge
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(150); await pg.click('.nav-add'); await pg.wait_for_timeout(200)
        await pg.evaluate("camTarget=null")
        await pg.set_input_files('#filePick', os.path.join(ROOT, 'tests', 'sample.jpg'))
        try: await pg.wait_for_selector('#fSugg [data-a=pickSugg]', timeout=30000)
        except Exception: pass
        n = await pg.locator('#fSugg [data-a=pickSugg]').count()
        check(n >= 1 and await pg.locator('#fPhotos .pt').count() == 1, f'{theme}: Fotoerkennung schlägt {n} Namen vor')
        if n:
            await shot('17-suggest')
            await pg.locator('#fSugg [data-a=pickSugg]').first.click()
            check(await pg.input_value('#fName') != '' and await pg.input_value('#fTags') != '', f'{theme}: Vorschlag füllt Name und Schlagwort')
        await pg.click('[data-a="cancelEdit"]'); await pg.wait_for_timeout(200)
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(200); await pg.click('.annex'); await pg.wait_for_timeout(300)
        # Suche per Foto: verändertes Foto vom Akkuschrauber findet ihn zuerst
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(150); await pg.click('.nav-add'); await pg.wait_for_timeout(200)
        await pg.fill('#fName', 'Dreieck-Schild'); await pg.evaluate("camTarget=null")
        await pg.set_input_files('#filePick', os.path.join(ROOT, 'tests', 'sample2.jpg')); await pg.wait_for_timeout(600)
        await pg.click('button[type=submit]'); await pg.wait_for_timeout(300)
        await pg.goto(BASE + '#/search'); await pg.wait_for_timeout(200)
        await pg.evaluate("camTarget={search:true}")
        await pg.set_input_files('#filePick', os.path.join(ROOT, 'tests', 'sample-alt.jpg'))
        await pg.wait_for_function("PS.state==='done'||PS.state==='error'", timeout=120000)
        top = await pg.evaluate("PS.results.map(r=>r.it.name)")
        check(await pg.evaluate("PS.state") == 'done' and top and top[0] == 'Akkuschrauber Bosch' and 'Dreieck-Schild' not in top[:1], f'{theme}: Suche per Foto findet das ähnliche Ding zuerst {top[:3]}')
        await pg.wait_for_timeout(300); await shot('18-photosearch')
        await pg.click('[data-a="psAdd"]'); await pg.wait_for_timeout(600)
        check('#/edit/new' in pg.url and await pg.locator('#fPhotos .pt').count() == 1, f'{theme}: aus Suchfoto einräumen übernimmt das Foto')
        check(await pg.locator('#fSugg .chip.own').count() >= 1 and await pg.locator('[data-a="dupPlus"]').count() == 1, f'{theme}: eigenes ähnliches Ding wird vorgeschlagen (Menge +1)')
        await pg.click('[data-a="cancelEdit"]'); await pg.wait_for_timeout(200)
        # Backup über das Teilen-Menü (hier ohne Teilen → Datei)
        await pg.goto(BASE + '#/more'); await pg.wait_for_function("document.querySelector('#bkState')?.textContent.includes('MB')", timeout=60000)
        async with pg.expect_download() as dl: await pg.click('[data-a="shareBackup"]')
        bk = json.load(open(await (await dl.value).path()))
        check(bk['app'] == 'lager' and len(bk['items']) == await pg.evaluate("S.items.length"), f'{theme}: Backup über „Auf Google Drive sichern“ (Rückfall Datei)')
        # Kamera mehrmals hintereinander benutzen
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(150); await pg.click('.nav-add'); await pg.wait_for_timeout(200)
        await pg.fill('#fName', 'Kameratest')
        for k in range(3):
            await pg.click('[data-a="fCam"]'); await pg.wait_for_timeout(900)
            await pg.tap('.cam-shot', timeout=5000); await pg.wait_for_timeout(700)
        check(await pg.locator('#fPhotos .pt').count() == 3, f'{theme}: Kamera dreimal hintereinander')
        await pg.click('[data-a="cancelEdit"]'); await pg.wait_for_timeout(200)
        await pg.goto(BASE + '#/'); await pg.wait_for_timeout(200); await pg.click('.annex'); await pg.wait_for_timeout(300)
        # Zurück-Taste schließt das Sheet, ohne die Seite zu verlassen
